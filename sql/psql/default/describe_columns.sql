SELECT a.attname::text AS "Column",
    pg_catalog.format_type(a.atttypid, a.atttypmod)::text AS "Type",
    (SELECT co.collname FROM pg_catalog.pg_collation co
        WHERE co.oid = a.attcollation AND a.attcollation <> ty.typcollation)::text
        AS "Collation",
    CASE WHEN a.attnotnull THEN 'not null' END::text AS "Nullable",
    CASE a.attidentity
        WHEN 'a' THEN 'generated always as identity'
        WHEN 'd' THEN 'generated by default as identity'
        ELSE pg_catalog.pg_get_expr(d.adbin, d.adrelid)
    END::text AS "Default"
{% if plus %}
    , CASE a.attstorage WHEN 'p' THEN 'plain' WHEN 'e' THEN 'external'
        WHEN 'm' THEN 'main' WHEN 'x' THEN 'extended' END::text AS "Storage",
    pg_catalog.col_description(a.attrelid, a.attnum)::text AS "Description"
{% endif %}
FROM t
JOIN pg_catalog.pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
JOIN pg_catalog.pg_type ty ON ty.oid = a.atttypid
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
ORDER BY a.attnum
