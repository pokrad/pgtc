-- Macros: a column definition. Needs `a` (pg_attribute) joined with coljoins().
{% macro coldef(generated) -%}
pg_catalog.quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
    || CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation
            THEN ' COLLATE ' || pg_catalog.quote_ident(cn.nspname) || '.' || pg_catalog.quote_ident(co.collname)
            ELSE '' END
    || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                          WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
{% if generated %}
    || CASE a.attgenerated
           WHEN 's' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
           WHEN 'v' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(ad.adbin, ad.adrelid) || ') VIRTUAL'
           ELSE '' END
{% endif %}
    || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
    || CASE WHEN ad.adbin IS NOT NULL{% if generated %} AND a.attgenerated = ''{% endif %}
            THEN ' DEFAULT ' || pg_catalog.pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END
{%- endmacro %}
{% macro coljoins() -%}
JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_catalog.pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
LEFT JOIN pg_catalog.pg_collation co ON co.oid = a.attcollation
LEFT JOIN pg_catalog.pg_namespace cn ON cn.oid = co.collnamespace
{%- endmacro %}
